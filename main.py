# ==============================================================================
# 🚀 ВЕЛИКИЙ ТА ДУШЕВНИЙ КОНСПЕКТ: АВТОМАТИЧНЕ СОРТУВАННЯ КАРТИНОК ЗА ДОПОМОГОЮ CNN
# ==============================================================================
#
# 💡 Головна ідея цього скрипта:
# У тебе є купа різних картинок у папці "images". Ти не хочеш вручну сидіти й
# розкладати їх по папках. Ця програма робить усе за тебе:
# 1. Бере розумну нейромережу (MobileNetV2), яка дивиться на кожне фото.
# 2. Перетворює враження від картинки у набір чисел ("числовий портрет").
# 3. Алгоритм DBSCAN порівнює ці портрети й шукає схожі фотографії.
# 4. Програма сама створює папочки та розкладає туди картинки!
#
# ==============================================================================
# 📦 КРОК 0: ІМПОРТУЄМО НАШІ ІНСТРУМЕНТИ (Бібліотеки)
# ==============================================================================

import shutil  # Наш "робот-вантажник": копіює та переносить файли між папками.
from pathlib import Path  # Зручна навігація по папках комп'ютера (і для Windows, і для Mac).
import numpy as np  # Король математики в Python: працює з масивами чисел та списками.
import tensorflow as tf  # Головний мозок: фреймворк, у якому живуть нейромережі.
from PIL import Image  # Наша фотокамера (Pillow): відкриває та змінює розмір зображень.
from sklearn.cluster import DBSCAN  # Детектив-сортувальник: шукає схожі картинки й групує їх без підказок.
from sklearn.preprocessing import normalize  # Ювелір: приводить усі числові вектори до єдиного стандарту.

# ==============================================================================
# ⚙️ КРОК 1: НАЛАШТУВАННЯ ТА НАШІ ГОЛОВНІ ПРАВИЛА
# ==============================================================================

# Де шукаємо фотографії? У папці 'images' поруч із цим файлом
IMAGE_DIR = Path('images')

# Куди будемо зберігати розсортовані папочки? У папку 'output'
OUTPUT_DIR = Path('output')

# Нейромережа MobileNetV2 любить, коли всі картинки однакового розміру.
# Тому стискаємо/розтягуємо кожне фото до 224 на 224 пікселі.
IMAGE_SIZE = (224, 224)

# Щоб комп'ютер не "завис", обробляємо фотографії не по одній, а порціями (батчами) по 16 штук.
BATCH_SIZE = 16

# ==============================================================================
# 🧠 КРОК 2: ЗАВАНТАЖУЄМО ВЖЕ НАВЧЕНУ НЕЙРОМЕРЕЖУ (MobileNetV2)
# ==============================================================================

# Замість того щоб навчати мережу тижнями, беремо готову MobileNetV2 від Google!
model = tf.keras.applications.MobileNetV2(
    weights='imagenet',  # Вона вже бачила мільйони фото з бази ImageNet і вміє відрізняти предмети.
    include_top=False,  # Відрізаємо "верхівку" (класифікатор) — нам не потрібен готовий вердикт,
    # нам потрібні тільки її "думки" та "ознаки" про картинку.
    pooling='avg',  # Усереднюємо складні матриці в один акуратний рядок чисел.
    input_shape=(*IMAGE_SIZE, 3)  # Кажемо мережі: чекай на вхід кольорові фото (RGB: 3 канали) 224x224.
)

# ==============================================================================
# 🔍 КРОК 3: ШУКАЄМО ВСІ ФОТОГРАФІЇ В ПАПЦІ
# ==============================================================================

# Перелічуємо всі формати картинок, які ми готові обробляти:
extensions = {'.jpg', '.jpeg', '.png', '.bmp', '.webp'}

# Заглядаємо в папку 'images' та всі її підпапки (через rglob) і вибираємо тільки картинки:
image_paths = [path for path in IMAGE_DIR.rglob('*') if path.suffix.lower() in extensions]

# Якщо папка порожня або ми не знайшли жодного зображення — зупиняємося і кажемо про це користувачу:
if not image_paths:
    raise ValueError('На жаль, у папці images не знайдено жодного зображення 😢')


# ==============================================================================
# 🛠️ КРОК 4: ФУНКЦІЯ ДЛЯ ПІДГОТОВКИ ЗОБРАЖЕННЯ
# ==============================================================================

def load_image(path):
    """
    Бере шлях до фотографії, відкриває її, робить кольоровою (RGB),
    змінює розмір до 224x224 і перетворює на масив чисел для нейромережі.
    """
    with Image.open(path) as img:
        # Відкриваємо, переводимо в стандартний RGB (ігноруємо прозорість PNG) і міняємо розмір
        img = img.convert('RGB').resize(IMAGE_SIZE)
        # Повертаємо у вигляді дробових чисел NumPy
        return np.asarray(img, dtype='float32')


# ==============================================================================
# 🎨 КРОК 5: НАТАУЧУЄМО МЕРЕЖУ "РОЗДЕЛЯТИ" ФОТО НА ОЗНАКИ (Екстракція)
# ==============================================================================

features = []  # Сюди будемо складати числові "вектори-портрети" кожної картинки

# Беремо список усіх знайдених шляхів до картинок і пробігаємося по ньому порціями по 16 штук:
for start in range(0, len(image_paths), BATCH_SIZE):
    # Вирізаємо шматочок списку (16 штук)
    batch_paths = image_paths[start:start + BATCH_SIZE]

    # Підвантажуємо ці 16 картинок і збираємо в один спільний пакунок (батч)
    batch = np.stack([load_image(path) for path in batch_paths])

    # Спеціальна нормалізація від розробників MobileNetV2 (приводить числа до потрібного формату)
    batch = tf.keras.applications.mobilenet_v2.preprocess_input(batch)

    # Нейромережа дивиться на 16 картинок і видає вектори їхніх ознак (без виводу зайвого логу: verbose=0)
    embeddings = model.predict(batch, verbose=0)

    # Зберігаємо отримані вектори
    features.append(embeddings)

# Зклеюємо всі окремі порції векторів в один великий список для всіх картинок одразу
features = np.concatenate(features, axis=0)

# Нормалізуємо вектори (зводимо їхню довжину до 1.0 за формулою L2),
# щоб далі порівнювати саме СОДЕРЖАНИЕ фотографій, а не їхню яскравість
features = normalize(features, norm='l2')

# ==============================================================================
# 🔮 КРОК 6: АВТОМАТИЧНЕ ГРУПУВАННЯ (Кластеризація через DBSCAN)
# ==============================================================================

# Створюємо розумний алгоритм DBSCAN, який сам знайде скупчення схожих фото:
clustering = DBSCAN(
    eps=0.3,  # Поріг схожості: чим менше це число, тим суворіше алгоритм шукає схожість.
    min_samples=2,  # Потрібно мінімум 2 схожі картинки, щоб створити окрему папку-кластер.
    metric='cosine',  # Використовуємо кут між векторами (косинусну відстань) для порівняння картинок.
)

# Запускаємо розрахунок: алгоритм видає номери груп (0, 1, 2...), а для унікальних фото видає -1
labels = clustering.fit_predict(features)

# ==============================================================================
# 📂 КРОК 7: СТВОРЮЄМО ПАПКИ ТА РОЗКЛАДАЄМО ФАЙЛИ
# ==============================================================================

# Переконуємося, що головна папка 'output' існує (якщо немає — створюємо)
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

# Проходимося по кожному файлу та його мітці (номеру групи), яку видав DBSCAN:
for path, label in zip(image_paths, labels):
    # Якщо label == -1, картинка унікальна і не має пари -> відправляємо в папку 'noise' (шум).
    # Якщо label >= 0, відправляємо у відповідну папку cluster_0, cluster_1 і т.д.
    folder_name = 'noise' if label == -1 else f'cluster_{label}'

    # Формуємо шлях до потрібної папочки
    target_dir = OUTPUT_DIR / folder_name
    target_dir.mkdir(parents=True, exist_ok=True)

    # Копіюємо файл із початкового місця в нову папку
    shutil.copy2(path, target_dir / path.name)

# ==============================================================================
# 📊 КРОК 8: ВИВОДИМО ГАРНУ СТАТИСТИКУ В КОНСОЛЬ
# ==============================================================================

# Отримуємо список усіх знайдених груп, ігноруючи шум (-1)
clusters = set(labels) - {-1}

# Рахуємо, скільки картинок не знайшли собі пари й потрапили в шум
noise_count = int(np.sum(labels == -1))

print("=" * 50)
print(f'🎉 Опрацювання завершено успішно!')
print(f'📸 Всього оброблено зображень: {len(image_paths)}')
print(f"📁 Створено папок-кластерів: {len(clusters)}")
print(f"❓ Потрапило в шум (унікальні фото без пари): {noise_count}")
print("=" * 50)

# Показуємо деталізацію по кожній знахідці:
for label in sorted(clusters):
    count = int(np.sum(labels == label))
    print(f"   • Кластер {label}: знайдено {count} схожих зображень")

print("=" * 50)